"""Re-run REAL SQLite checks, unit tests, service check, and truthful integration status.

This script never fabricates graph or LLM execution. Live evidence is generated
separately by scripts/live_end_to_end.py ONLY after actual success.
"""
import json
import os
import sqlite3
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))
from schemaguard.cli import load_env,load_fixture
from schemaguard.fixtures import version_of
from schemaguard.sqlcheck import execute_plan,example_plans
from schemaguard.graph import GraphStore
from schemaguard import queries

load_env()
f=load_fixture()
TARGET='users.legacy_status'

def simplified(p, result):
    return {"label":p['label'],"scope":p['scope'],"status":result['status'],
        "verified":result['verified'],"actions":result['actions'],"applied":result['applied'],
        "failures":result['affected_sql_failures'],
        "sqlite_errors":{k:v['error'] for k,v in result['after'].items() if v['error']},
        "checks":result['checks'],"step_checks":result['step_checks'],
        "latest_only_would_pass":result['latest_only_would_pass'],"duration_ms":result['duration_ms']}

checks=[simplified(p,execute_plan(f,TARGET,p['actions'])) for p in example_plans(TARGET,f)]
unused=execute_plan(f,'users.retired_flag', [{'type':'drop_column','target':'users.retired_flag'}])
renamed=json.loads(json.dumps(f))
worker=next(c for c in renamed['consumers'] if c['kind']=='worker')
worker['id']='alerts-job-v9'
worker['version']='9.0'
worker['projection']=['id','name']
changed=execute_plan(renamed,TARGET,[{'type':'drop_column','target':TARGET}])
required=json.loads(json.dumps(f))
next(c for c in required['consumers'] if c['kind']=='worker')['required_output'].append('legacy_status')
unresolved=execute_plan(required,TARGET,example_plans(TARGET,required)[-1]['actions'])
proc=subprocess.run([sys.executable,'-m','pytest','-q'],cwd=ROOT,text=True,capture_output=True,timeout=50)
(ROOT/'evidence'/'pytest-output.txt').write_text(proc.stdout+'\n'+proc.stderr,encoding='utf8')
connectivity={"real_graph_cypher":"blocked", "real_path_traversal":"not_run"}
try:
    graph=GraphStore()
    connectivity['real_graph_cypher']='passed' if graph.ping() else 'failed'
    paths=graph.query(queries.ALL_PATHS,read=True)
    connectivity['real_path_traversal']='passed'
    connectivity['path_rows']=len(paths)
    ctx=graph.context(f,TARGET)
    connectivity['evidence_state']=ctx['state']
    connectivity['affected_from_real_graph']=[x['consumer'] for x in ctx['affected']]
except Exception as exc:
    connectivity['blocker_type']=type(exc).__name__
    connectivity['blocker']='FalkorDB server or SDK unavailable; no graph claim made'

live_file=ROOT/'evidence'/'live-falkordb-agent-results.json'
# The presence of an evidence file alone is not treated as proof of this run.
# Only explicit REAL graph + LLM evidence file generated by acceptance script is described.
report={
    "generated_at_ist":datetime.now(ZoneInfo('Asia/Kolkata')).isoformat(),
    "environment":{"python":sys.version.split()[0],"sqlite":sqlite3.sqlite_version,
       "fixture_version":version_of(f),"model_api_key_configured":bool(os.getenv('OPENAI_API_KEY'))},
    "executed_sql_checks":checks,
    "unused_field":{"verified":unused['verified'],"status":unused['status'],"checks":unused['checks']},
    "changed_worker_offline_sql":{"label":"worker renamed and target read removed", "fixture_version":version_of(renamed),
        "verified":changed['verified'],"failed_consumers":changed['affected_sql_failures']},
    "required_output_unresolved":{"verified":unresolved['verified'],
        "affected_sql_failures":unresolved['affected_sql_failures'],
        "unresolved_required_outputs":unresolved['unresolved_required_outputs']},
    "test_runner":{"exit_code":proc.returncode,"stdout":proc.stdout.strip()},
    "graph_connectivity":connectivity,
    "llm_integration":{"configured":bool(os.getenv('OPENAI_API_KEY')),
        "live_model_tool_calls_executed_in_this_report":False,
        "separate_live_acceptance_script":"python scripts/live_end_to_end.py",
        "separate_live_evidence_exists":live_file.exists()},
    "frontend_checks":{"javascript_syntax":"checked separately with node --check",
        "chromium_browsing":"real static UI with Python HTTP proxy to actual localhost backend",
        "screenshots":["evidence/ui-continuation-sql.png","evidence/ui-continuation-agent-blocked.png"],
        "full_graph_agent_video":"not_recorded"},
}
(ROOT/'evidence'/'verification-results.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf8')
print('Report:',ROOT/'evidence'/'verification-results.json')
print('Tests:',proc.stdout.strip().splitlines()[-1] if proc.stdout else 'no test output')
print('Graph:',connectivity)
print('Model: not executed by this report')
if proc.returncode:raise SystemExit(proc.returncode)
